`timescale 1ns / 1ps

module DataPath(
    input        Clock,
    input        RegDst,
    input        Branch,
    input        MemRead,
    input        MemWrite,
    input        RegWrite,
    input        MemToReg,
    input        ALUSrc,
    input  [1:0] ALUOp,
    output [2:0] opcode
);

reg  [15:0] pc_initial;
wire [15:0] pc_next, pc4;
wire [15:0] instruction;
wire [2:0]  mux_regfile;
wire [15:0] readData1, readData2, writeData;
wire [15:0] mux_ALU, ALU_Out, Zgjerimi, memToMux;
wire [15:0] shifter2beq, beqAddress;
wire [3:0]  ALUCtrl;
wire        zerof, overflow, carryout;
wire        andMuxBranch;

// ?? PC ???????????????????????????????????????????????????????
initial
    pc_initial = 16'd10;

always @(posedge Clock)
    pc_initial <= pc_next;

assign pc4 = pc_initial + 16'd2;

// ?? Branch offset: sign-extend imm[6:0] then left-shift by 1
assign shifter2beq = {{8{instruction[6]}}, instruction[6:0], 1'b0};

// ?? Instruction Fetch ????????????????????????????????????????
InstructionMemory IM(pc_initial, instruction);

// ?? Register destination mux ?????????????????????????????????
// R-type (RegDst=1): write to RD=instruction[6:4]
// I-type (RegDst=0): write to RT=instruction[9:7]
assign mux_regfile = (RegDst == 1'b1) ? instruction[6:4] : instruction[9:7];

// ?? Sign-extension of 7-bit immediate ???????????????????????
assign Zgjerimi = {{9{instruction[6]}}, instruction[6:0]};

// ?? Register File ?????????????????????????????????????????????
// Port order MUST match RegisterFile declaration:
// RS, RT, RD, WriteData, ReadRS, ReadRT, RegWrite, Clock
RegisterFile RF(
    instruction[12:10],  // RS
    instruction[9:7],    // RT
    mux_regfile,         // RD
    writeData,           // WriteData
    readData1,           // ReadRS  ? output (was wrongly swapped with RegWrite)
    readData2,           // ReadRT  ? output (was wrongly swapped with Clock)
    RegWrite,            // RegWrite
    Clock                // Clock
);

// ?? ALU source mux ???????????????????????????????????????????
assign mux_ALU = (ALUSrc == 1'b1) ? Zgjerimi : readData2;

// ?? ALU Control ??????????????????????????????????????????????
ALU_Control AC(
    instruction[15:13],  // opcode
    ALUOp,
    instruction[3:0],    // Funct
    ALUCtrl
);

// ?? ALU ??????????????????????????????????????????????????????
ALU_16bit ALU(
    readData1,
    mux_ALU,
    ALUCtrl[2:0],
    ALUCtrl[3],
    zerof,
    overflow,
    carryout,
    ALU_Out
);

// ?? Data Memory ??????????????????????????????????????????????
DataMemory DM(
    ALU_Out,    // address
    readData2,  // WriteData for SW
    Clock,
    MemWrite,
    MemRead,
    memToMux
);

// ?? Write-back mux ???????????????????????????????????????????
assign writeData = (MemToReg == 1'b1) ? memToMux : ALU_Out;

// ?? BNE branch condition ?????????????????????????????????????
// Branch when zerof=0 (rs != rt)
assign andMuxBranch = ~(~zerof & Branch);

// ?? Branch target ????????????????????????????????????????????
assign beqAddress = pc4 + shifter2beq;

// ?? Next PC ??????????????????????????????????????????????????
assign pc_next = (andMuxBranch == 1'b1) ? pc4 : beqAddress;

// ?? Opcode output to ControlUnit ?????????????????????????????
assign opcode = instruction[15:13];

endmodule
